"""
Handwritten Text Rendering Engine
==================================
Transforms plain text into realistic handwritten PDFs by applying
controlled randomization on a per-character basis.

Key imperfection algorithms:
  - Multi-font random swapping per character
  - Per-character rotation & independent X/Y scale
  - Per-character ink opacity (pen pressure)
  - Per-character baseline jitter (Y micro-offset)
  - Per-line slope drift (writing tilts up or down)
  - Per-line sinusoidal waviness (organic micro-wobble)
  - Controlled kerning variation (X spacing)
  - Word wrapping & automatic pagination
  - Progressive fatigue degradation (writing gets worse over time)
  - Optional glyph bank: the writer's own letters / joined pieces cut from
    scans (glyphbank.py), preferred over fonts, re-slanted to the writer's slant
  - Optional handwriting model: whole lines generated by Emuru in the writer's
    style (wordmodel.py), laid out with the same margins / slope / pagination
"""


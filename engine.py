@dataclass
class EngineConfig:
    """All tuneable knobs for the rendering engine."""

    # Page geometry (A4 at 150 DPI)
    page_width: int = 1240
    page_height: int = 1754
    margin_top: int = 100
    margin_bottom: int = 100
    margin_left: int = 100
    margin_right: int = 100

    # Typography
    font_size: int = 42
    line_height: int = 60

    # ── Imperfection: positioning ──────────────────────────────────────────
    # Letter spacing — base extra pixels between characters (float for sub-px).
    letter_spacing: float = 1.0
    # Letter spacing jitter — random variation on top of base spacing.
    letter_spacing_jitter: Tuple[float, float] = (-1.0, 3.0)

    # Baseline jitter — per-character vertical micro-offset.
    baseline_jitter: Tuple[float, float] = (-3.0, 3.0)

    # Line slope — each new line gets a random slope coefficient.
    slope_range: Tuple[float, float] = (-0.015, 0.015)
    # Mid-line slope drift — slope changes slightly as writing progresses.
    slope_drift: float = 0.003

    # Multi-harmonic waviness (layered sine waves = less patterned).
    wave_amplitude: float = 2.5
    wave_period_range: Tuple[float, float] = (200.0, 500.0)
    # Number of harmonic layers (more = more chaotic baseline).
    wave_harmonics: int = 3

    # Left margin jitter — each new line starts slightly differently.
    margin_left_jitter: Tuple[float, float] = (-6.0, 10.0)

    # Per-character random noise on Y (adds unpredictability).
    noise_y_range: Tuple[float, float] = (-1.0, 1.0)

    # Micro-pause probability — chance of a small extra gap between chars.
    micro_pause_probability: float = 0.06
    micro_pause_range: Tuple[float, float] = (2.0, 6.0)

    # ── Imperfection: shape ────────────────────────────────────────────────
    rotation_range: Tuple[float, float] = (-3.5, 3.5)
    scale_x_range: Tuple[float, float] = (0.93, 1.07)
    scale_y_range: Tuple[float, float] = (0.94, 1.06)

    # ── Imperfection: ink ──────────────────────────────────────────────────
    opacity_range: Tuple[int, int] = (180, 255)
    ink_color: Tuple[int, int, int] = (20, 20, 22)       # black ballpoint

    # ── Spacing ────────────────────────────────────────────────────────────
    word_spacing: Tuple[float, float] = (10.0, 18.0)
    paragraph_spacing: float = 30.0
    line_gap_jitter: Tuple[float, float] = (-5.0, 10.0)

    # ── Word-level baseline ────────────────────────────────────────────────
    word_level_baseline: bool = True
    word_jitter_y: Tuple[float, float] = (-3.0, 3.0)

    # ── Subtle drift (breaks visible patterns) ─────────────────────────────
    # Very mild progressive variation so the output doesn't look like
    # it follows a repeating pattern.  NOT meant to make things messy.
    fatigue_enabled: bool = True
    # How quickly drift builds per character (very slow = subtle).
    fatigue_rate: float = 0.002
    # Maximum drift multiplier (1.0 = none, 1.4 = barely noticeable).
    fatigue_max: float = 1.15
    # Recovery at paragraph breaks (keeps drift from accumulating).
    fatigue_paragraph_recovery: float = 0.5
    # Recovery at line breaks.
    fatigue_line_recovery: float = 0.15
    # Rare micro-bursts of slightly different parameters.
    fatigue_burst_probability: float = 0.02
    # Burst multiplier (subtle).
    fatigue_burst_multiplier: Tuple[float, float] = (1.1, 1.3)

    # ── Glyph bank (letters cut from the writer's own scans) ───────────────
    # Folder with bank.json (see glyphbank.py); None = fonts only.
    glyph_bank: Optional[str] = None
    # Slant re-applied to bank glyphs in degrees (+ = right); None = writer's measured slant.
    slant_deg: Optional[float] = None
    # Pixel overlap between consecutive bank pieces in a word (re-joins cut strokes).
    join_overlap: float = 2.0
    # Generate whole lines with the Emuru handwriting model, styled by the glyph
    # bank's labeled words (wordmodel.py). Needs glyph_bank; slow without a GPU.
    handwriting_model: bool = False
    # With a glyph bank that has layout.json (glyphbank.py measure): use the writer's
    # measured x-height, line pitch, margins, word gaps, line drift and stroke width
    # instead of the size / spacing settings above.
    writer_layout: bool = True
    # How much each reuse of a bank piece is varied (0 = exact copies, 1 = natural,
    # 2 = loose): shape wobble, per-word slant change, stroke redraw for pad samples.
    # Shape wobble on reused pieces / font letters (0 = none). Set to 2 % on request;
    # 0.6 read best in the legibility test, 1.0 distorted letters.
    glyph_variation: float = 0.0     # off: it looked artificial (variety now from copies + per-word lean/tilt/weight)
    # Per-word variation that keeps letter shapes intact: lean (slant change, degrees sd),
    # tilt (rotation around the word's start, degrees sd), size (sd) and pen weight
    # (strokes up to this much lighter / 45 % of it heavier).
    word_lean_deg: float = 2.0
    word_tilt_deg: float = 1.2
    word_size_var: float = 0.06
    word_weight_var: float = 0.18
    # Pad samples are redrawn along a slightly different smooth pen path each time
    # (natural variation, not distortion) — independent of the wobble above.
    pad_redraw_variation: float = 0.0   # pad samples redrawn exactly as written
    # Multiplies the distance between lines (on top of line_height or the writer's
    # measured line pitch): 1.0 = as measured, 1.5 = one and a half spacing.
    line_spacing: float = 1.0
    # Each use of a pad sample redrawn a little differently (letter spacing, baseline
    # curve, where dots/crosses land): a repeated word never looks like the same picture
    pad_variation: float = 1.0
    # Letter width on top of the bank's measured pad->paper widening (1.0 = as measured)
    letter_width: float = 1.0
    # How uneven the gaps between lines are (0 = ruler-perfect, 1 = natural, 2 = loose).
    line_irregularity: float = 1.0
    # Space letters by their ink (closest approach to the previous letter = the writer's
    # measured letter gap) instead of by bounding boxes.
    ink_spacing: bool = True
    # Share of neighbouring lowercase letters joined by a connecting stroke (measured on
    # the writer's scans: ~0.27 of letter pairs are joined). 0 = never.
    letter_joins: float = 0.1   # paper samples: separate letters; the occasional join
    # Reading check: a handwriting recogniser reads each assembled word back and the
    # word is rewritten (up to 2 more tries) if it doesn't read right. ~60 ms/word on GPU.
    proofread: bool = False
    # Make pages look scanned/photographed (paper tone, grain, ink bleed, tiny rotation).
    scan_look: bool = False
    # Ink soaking into paper: feathered stroke edges and uneven ballpoint flow (0 = off).
    ink_texture: float = 0.4
    # The next page's writing faintly visible through the sheet (it's on the back).
    show_through: bool = False
    show_through_strength: float = 0.5
    # Keep every word as its own layer so single words can be re-rolled or replaced
    # after generating (web editor). Costs some memory per page.
    editable: bool = True
    # After a "?" the next words start on a new line (a little extra space, slight indent)
    question_break: bool = True
    # Measured in the writer's multi-page samples: over the first 2-3 pages the
    # writing grows ~25 %, word gaps tighten ~15 % and sizes vary more, then it
    # plateaus. 0 = every page like page 1, 1 = as measured.
    page_progression: float = 0.0          # off by default: later pages looked worse
    # AI model only: how much of the writer's irregularity is added back to the model's
    # neat output (per-word size / slant / baseline spread and shape wobble). 0 = as generated.
    model_messiness: float = 1.0
    # Strip Markdown before writing (#-headings, **bold**, `code`, [link](url), "* " bullets
    # become "- "): nobody hand-writes the markup.
    clean_markdown: bool = True
    # Render Markdown as a document: headings, lists, hand-drawn tables, ```mermaid
    # flowcharts, $LaTeX$ math, code, ![sketch](pad:name) drawings (docrender.py).
    structured: bool = True
    # Font letters (for characters the writer hasn't provided) are drawn from the font's
    # outlines with a fresh smooth deformation each time (vectorfont.py).
    vector_fonts: bool = True
    # Redraw every scanned / photographed / generated piece along its centre line with
    # one pen (the writer's measured width): sources written with different pens or
    # captured at different quality then match, and edges come out smooth.
    uniform_pen: bool = True
    # Output resolution. All pixel sizes above are given at 150 DPI and scaled to
    # this; 300 keeps strokes sharp on paper (150 prints soft and pixelated).
    dpi: int = 300



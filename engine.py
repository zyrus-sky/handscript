def paste_multiply(dst: Image.Image, src: Image.Image, xy) -> None:
    """Paste RGBA ink onto dst (RGBA, in place) the way ink layers on paper: where it
    lands on paper it's just its colour; where it lands on ink already there, the two
    multiply (two half-transparent layers make a darker spot, like crossings and joins
    in real writing). W3C "multiply" blend with source-over compositing."""
    x, y = int(xy[0]), int(xy[1])
    x0, y0 = max(0, x), max(0, y)
    x1, y1 = min(dst.width, x + src.width), min(dst.height, y + src.height)
    if x1 <= x0 or y1 <= y0:
        return
    sc = src.crop((x0 - x, y0 - y, x1 - x, y1 - y)).convert("RGBA")
    S = np.asarray(sc)
    if S[..., 3].max() == 0:
        return
    box = (x0, y0, x1, y1)
    dc = dst.crop(box).convert("RGBA")
    D = np.asarray(dc)
    out = Image.alpha_composite(dc, sc)                 # plain paper: normal compositing (fast)
    ov = (S[..., 3] > 0) & (D[..., 3] > 0) & (D[..., :3].min(-1) < 250)
    if ov.any():                                        # ink on ink: multiply, only there
        s = S[ov].astype(np.float32) / 255
        d = D[ov].astype(np.float32) / 255
        As, Ad = s[:, 3:], d[:, 3:]
        Ao = As + Ad * (1 - As)
        prem = As * Ad * (s[:, :3] * d[:, :3]) + As * (1 - Ad) * s[:, :3] + Ad * (1 - As) * d[:, :3]
        O = np.array(out)
        O[ov] = np.clip(np.concatenate([prem / np.maximum(Ao, 1e-6), Ao], 1) * 255 + 0.5, 0, 255).astype(np.uint8)
        out = Image.fromarray(O, "RGBA")
    dst.paste(out, (x0, y0))


class HandwritingEngine:
    """Core rendering engine."""

    def __init__(
        self,
        font_paths: List[str],
        config: Optional[EngineConfig] = None,
    ) -> None:
        self.cfg = self._at_dpi(config or EngineConfig())
        self.fonts: List[ImageFont.FreeTypeFont] = self._load_fonts(font_paths)
        # Baseline sits this far below the line's top; bank letters are scaled
        # so their x-height matches the first font's.
        self._ascent: float = float(self.fonts[0].getmetrics()[0])
        xb = self.fonts[0].getbbox("x")
        self._x_height: float = float(max(1, xb[3] - xb[1]))
        self._stroke_px: Optional[float] = None
        self._fallback_fonts: List[ImageFont.FreeTypeFont] = []
        self._letter_gap_q: Tuple[float, float, float] = (0.15, 0.3, 0.5)   # x-heights
        self._prev_right: Optional[dict] = None
        self._prev_tok: str = ""
        self._line_rhythm: float = 0.0
        self._origin: Tuple[int, int] = (0, 0)     # page position of the active canvas
        self._after_question = False
        self._last_space = 0.0
        self.word_recs: list = []
        self.page_bases: list = []
        self.raw_pages: list = []
        self._pressure: float = float(sum(self.cfg.opacity_range)) / 2
        self._word_slant: float = 0.0
        self._word_tilt: float = 0.0
        self._word_x0: float = 0.0
        self._word_pen: float = 1.0
        self._word_scale: float = 1.0
        self._page_scale: float = 1.0       # page-to-page growth (page_progression)
        self._page_variation: float = 1.0
        self._page_gap: float = 1.0
        layout = load_layout(self.cfg.glyph_bank) if self.cfg.glyph_bank and self.cfg.writer_layout else None
        if layout:
            self._apply_writer_layout(layout, font_paths)
        if abs(self.cfg.line_spacing - 1.0) > 1e-3:
            self.cfg = replace(self.cfg, line_height=max(1, round(self.cfg.line_height * self.cfg.line_spacing)))
        self.bank: Optional[GlyphBank] = GlyphBank(self.cfg.glyph_bank) if self.cfg.glyph_bank else None
        from morph import MorphModel
        self._morph = MorphModel(self.cfg.glyph_bank) if self.cfg.glyph_bank and self.cfg.vector_fonts else None
        self._choose_fallback_fonts()
        slant = self.cfg.slant_deg if self.cfg.slant_deg is not None else (self.bank.slant_deg if self.bank else 0.0)
        self._slant_t: float = math.tan(math.radians(slant))
        self.pages: List[Image.Image] = []
        self.fallback_used: Counter = Counter()
        self._canvas: Optional[Image.Image] = None
        self._draw: Optional[ImageDraw.ImageDraw] = None
        self._x: float = 0.0
        self._y: float = 0.0
        self._line_slope: float = 0.0
        self._line_start_x: float = 0.0
        self._line_char_index: int = 0
        self._word_y_offset: float = 0.0
        # Multi-harmonic wave state (list of (period, phase, amplitude_scale))
        self._harmonics: List[Tuple[float, float, float]] = []
        # Character cache: {(char, font_index, opacity_bucket, scale_x_bucket, scale_y_bucket, rotation_bucket): Image.Image}
        self._char_cache: dict = {}
        # ── Fatigue state ──────────────────────────────────────────────────
        self._fatigue: float = 0.0          # Current drift level (0.0 → 1.0)
        self._total_chars_written: int = 0  # Global character counter
        self._per_char_seed: int = 0        # Shifts random state per character

    # ── font loading ──────────────────────────────────────────────────────

    # Pixel-valued settings (given at 150 DPI) rescaled by _at_dpi.
    _PX_FIELDS = (
        "page_width", "page_height", "margin_top", "margin_bottom", "margin_left", "margin_right",
        "font_size", "line_height", "letter_spacing", "letter_spacing_jitter", "baseline_jitter",
        "wave_amplitude", "wave_period_range", "margin_left_jitter", "noise_y_range",
        "micro_pause_range", "word_spacing", "paragraph_spacing", "line_gap_jitter",
        "word_jitter_y", "join_overlap",
    )

    @classmethod
    def _at_dpi(cls, cfg: EngineConfig) -> EngineConfig:
        k = cfg.dpi / 150.0
        if abs(k - 1.0) < 1e-6:
            return cfg
        changes = {}
        for name in cls._PX_FIELDS:
            v = getattr(cfg, name)
            if isinstance(v, tuple):
                changes[name] = tuple(x * k for x in v)
            elif isinstance(v, int):
                changes[name] = int(round(v * k))
            else:
                changes[name] = v * k
        return replace(cfg, **changes)

    def _apply_writer_layout(self, lay: dict, font_paths: List[str]) -> None:
        """Size and space everything like the writer's scanned pages (ratios of page
        width / x-height from glyphbank.measure_layout). Fallback fonts are resized
        so their x-height matches too."""
        W = self.cfg.page_width
        xh = lay["x_height"] * W
        pitch = lay["line_pitch"] * W
        jit = min(lay["line_pitch_jitter"] * W, 0.12 * pitch)
        sl = min(lay["slope_std"], 0.01)
        self.cfg = replace(
            self.cfg,
            font_size=max(8, round(self.cfg.font_size * xh / self._x_height)),
            line_height=round(pitch),
            line_gap_jitter=(-jit, jit),
            paragraph_spacing=min(lay["paragraph_extra"] * W, pitch),
            margin_left=max(40, round(lay["margin_left"] * W)),
            margin_right=max(40, round(lay["margin_right"] * W)),
            margin_top=max(50, round(lay["margin_top"] * W)),
            word_spacing=tuple(g * xh for g in lay["word_gap"]),
            slope_range=(lay["slope_mean"] - sl, lay["slope_mean"] + sl),
            opacity_range=(240, 255),       # ballpoint ink is near-solid; grey ink prints as halftone
        )
        self.fonts = self._load_fonts(font_paths)
        self._x_height = xh
        self._ascent = 2.0 * xh            # room for ascenders above the x-height
        self._stroke_px = lay["stroke"] * xh
        if lay.get("letter_gap"):
            self._letter_gap_q = tuple(lay["letter_gap"])

    def _widen(self, g) -> float:
        """Horizontal scale for a bank piece: pad pieces get the bank's measured
        tablet->paper widening; everything the user's letter-width setting."""
        strokes = g.get("strokes") if isinstance(g, dict) else g.strokes
        k = self.cfg.letter_width
        if strokes and self.bank is not None:
            k *= getattr(self.bank, "pad_stretch", 1.0)
        return k

    def _pen_width(self) -> float:
        """Target pen width (px) for the current word: the same for scanned pieces
        (_repen) and pad strokes (render_strokes), so letters within a word match."""
        # 0.115 x-heights: matched against an unprocessed phone photo of the notebook
        # (0.10-0.12; a 0.25-0.45 mm ballpoint line at a ~3.4 mm x-height)
        return max(self._stroke_px or 0.0, 0.115 * self._x_height) * self._word_pen

    def _repen(self, mask: Image.Image) -> Image.Image:
        """Re-ink a piece with a uniform pen: smooth, threshold, thin to the centre line
        (the path the pen travelled), then draw that path at the target width with an
        anti-aliased edge. Falls back to the input for tiny marks."""
        width = self._pen_width()
        a = np.array(mask, np.float32)
        if a.size == 0 or a.max() < 100:
            return mask
        sm = cv2.GaussianBlur(a, (0, 0), max(0.8, 0.18 * width))
        # threshold relative to this piece's own ink: small / thin letters keep their strokes
        strong = sm[sm > 20]
        thr = min(110.0, 0.45 * float(np.percentile(strong, 95))) if strong.size else 110.0
        ink = (sm > thr).astype(np.uint8)
        ink = cv2.morphologyEx(ink, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))
        if ink.sum() < 6:
            return mask
        if width >= 5 and min(ink.shape) >= 16:
            # thick strokes: find the centre line on a half-size copy (4x less work),
            # then put its points back at full resolution
            half = cv2.resize(ink, (ink.shape[1] // 2, ink.shape[0] // 2), interpolation=cv2.INTER_AREA)
            sk = _thin(half)
            ys2, xs2 = np.nonzero(sk)
            skel = np.zeros_like(ink)
            skel[np.clip(ys2 * 2, 0, ink.shape[0] - 1), np.clip(xs2 * 2, 0, ink.shape[1] - 1)] = 1
            # join the doubled-up points so the centre line stays connected
            skel = cv2.dilate(skel, np.ones((2, 2), np.uint8)) & ink
            skel = _thin(skel)
        else:
            skel = _thin(ink)
        if skel.sum() < 3:
            return mask
        # A real pen's line swells and thins (pressure, direction). Keep the piece's own
        # thickness profile along the centre line, normalised so its average matches
        # the target pen: consistent weight between sources, natural variation within.
        own = cv2.distanceTransform(ink, cv2.DIST_L2, 5)            # half-width inside ink
        ys, xs = np.nonzero(skel)
        prof = own[ys, xs]
        rel = (prof / max(1e-3, float(np.median(prof)))) ** 0.7
        r_pts = (width / 2.0) * np.clip(rel, 0.55, 1.6)
        # slow ballpoint wobble so even uniform sources don't come out monoline
        r_pts *= 1.0 + 0.12 * np.sin(xs / max(2.0, 1.7 * self._x_height) * 6.3 + random.uniform(0, 6.3))
        # each pixel takes the radius of its nearest centre-line point
        dist, lab = cv2.distanceTransformWithLabels((1 - skel).astype(np.uint8), cv2.DIST_L2, 5,
                                                    labelType=cv2.DIST_LABEL_PIXEL)
        rad = np.zeros(lab.max() + 1, np.float32)
        rad[lab[ys, xs]] = r_pts
        out = np.clip(rad[lab] + 0.5 - dist, 0.0, 1.0)
        return Image.fromarray((out * 255).astype(np.uint8), "L")

    def _match_stroke(self, mask: Image.Image) -> Image.Image:
        """Thicken thin generated strokes towards the writer's measured pen width
        (or re-ink with a uniform pen when uniform_pen is on)."""
        if self.cfg.uniform_pen:
            return self._repen(mask)
        if not self._stroke_px:
            return mask
        a = np.array(mask)
        ink = (a > 100).astype(np.uint8)
        contours, _ = cv2.findContours(ink, cv2.RETR_LIST, cv2.CHAIN_APPROX_NONE)
        perim = sum(cv2.arcLength(c, True) for c in contours)
        if perim <= 0:
            return mask
        diff = self._stroke_px - 2.0 * float(ink.sum()) / perim
        grown = cv2.dilate(a, np.ones((3, 3), np.uint8))    # +~2 px stroke width
        while diff >= 1.6:
            a, diff = grown, diff - 2.0
            grown = cv2.dilate(a, np.ones((3, 3), np.uint8))
        if diff >= 0.3:                                      # partial: blend a fraction of the growth
            w = min(1.0, 0.25 + 0.5 * diff)
            a = np.maximum(a, (grown * w).astype(np.uint8))
        return Image.fromarray(a, "L")

    def _load_fonts(self, paths: List[str]) -> List[ImageFont.FreeTypeFont]:
        fonts = []
        for p in paths:
            fp = Path(p)
            if not fp.exists():
                raise FileNotFoundError(f"Font file not found: {p}")
            fonts.append(ImageFont.truetype(str(fp), self.cfg.font_size))
        if not fonts:
            raise ValueError("At least one font path must be provided.")
        return fonts

    def _random_font(self) -> ImageFont.FreeTypeFont:
        # one font per word (chosen in _next_word_style), varied between words
        if self.__dict__.get("_word_font") is not None:
            return self._word_font
        return random.choice(self._fallback_fonts or self.fonts)

    def _render_vector_char(self, char: str, font: ImageFont.FreeTypeFont) -> Optional[Tuple[Image.Image, float]]:
        """Font letter drawn from its outline with a fresh smooth deformation
        (vectorfont.py), sized to the writer's proportions, slanted like the hand."""
        import vectorfont
        from glyphbank import TALL
        path = getattr(font, "path", None)
        params = None
        if self._morph and char.isalnum():
            # learned: the writer's form of this letter (which font) and how it deforms
            cands = [f.path for f in (self._fallback_fonts or self.fonts) if getattr(f, "path", None)]
            form_font, params = self._morph.sample(char, cands, self.cfg.glyph_variation)
            if form_font and vectorfont.supports(form_font, char):
                path = form_font
        if not path or not vectorfont.supports(path, char):
            return None
        body = (1.80 if char in TALL else 1.06) if char.isalnum() else None
        k = self._word_scale * self._page_scale
        res = vectorfont.render(path, char, self._x_height * k, body_target=body,
                                variation=self.cfg.glyph_variation,
                                slant_t=self._slant_t + self._word_slant, morph=params,
                                width_xh=(self._morph.width(char) * random.uniform(0.93, 1.07)
                                          if params is not None and self._morph.width(char) else None))
        if res is None:
            return None
        mask, base = res
        # fonts sometimes have tiny decorative holes at stroke ends: fill them
        a = (np.array(mask) > 100).astype(np.uint8)
        inv = 1 - a
        n, lab, st, _ = cv2.connectedComponentsWithStats(inv, connectivity=4)
        small = 0.04 * (self._x_height * k) ** 2
        arr = np.array(mask)
        for i in range(1, n):
            x, y, w, h, area = st[i]
            touches = x == 0 or y == 0 or x + w >= a.shape[1] or y + h >= a.shape[0]
            if not touches and area < small:
                arr[lab == i] = 255
        self._advance_fatigue()
        return self._ink(self._match_stroke(Image.fromarray(arr, "L"))), base

    def _font_cost(self, ch: str) -> float:
        """Planner cost of writing `ch` with a font letter: cheap when the morph model
        has learned the writer's form of it (fresh variants instead of reusing the same
        few pieces), expensive otherwise."""
        if self._morph and self._morph.m and ch in self._morph.m["chars"]:
            forms = self._morph.m["chars"][ch]["forms"]
            if any(f["resid"] < 0.05 for f in forms):
                return 1.9       # a learned letter: only when real pieces are scarce (1.3 put ~30% of letters on the font)
        return 2.2

    def _font_proportion(self, font: ImageFont.FreeTypeFont, char: str) -> float:
        from glyphbank import TALL
        if not char.isalnum():
            return 1.0
        key = (id(font), char)
        cache = self.__dict__.setdefault("_prop_cache", {})
        if key not in cache:
            try:
                body = -font.getbbox(char, anchor="ls")[1]
                fxh = -font.getbbox("x", anchor="ls")[1]
            except (ValueError, TypeError):
                body, fxh = 0, 0
            if body <= 0 or fxh <= 0:
                cache[key] = 1.0
            else:
                target = (1.80 if char in TALL else 1.06) * fxh
                cache[key] = float(min(1.5, max(0.8, target / body)))
        return cache[key]

    def _choose_fallback_fonts(self) -> None:
        """With a glyph bank, missing letters use only the font(s) whose letters look
        most like the writer's own (mean overlap of normalised letter shapes), instead
        of a random font per letter."""
        self._fallback_fonts = []
        if not self.bank or len(self.fonts) < 2:
            return
        letters = [l for l in self.bank._meta if len(l) == 1 and l.isalpha()][:24]
        if len(letters) < 5:
            return

        def norm(a: np.ndarray) -> np.ndarray:
            ys, xs = np.where(a > 100)
            if len(ys) == 0:
                return np.zeros((40, 40), np.float32)
            a = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
            h, w = a.shape
            k = 36.0 / max(h, w)
            a = cv2.resize(a, (max(1, round(w * k)), max(1, round(h * k))), interpolation=cv2.INTER_AREA)
            out = np.zeros((40, 40), np.float32)
            out[2:2 + a.shape[0], 2:2 + a.shape[1]] = a > 100
            return cv2.dilate(out, np.ones((3, 3), np.uint8))

        mine = {l: norm(np.array(self.bank.load(self.bank._meta[l][0]).mask)) for l in letters}
        scores = []
        for fi, font in enumerate(self.fonts):
            ious = []
            for l, m in mine.items():
                bb = font.getbbox(l)
                if bb[2] <= bb[0]:
                    continue
                im = Image.new("L", (bb[2] - bb[0] + 4, bb[3] - bb[1] + 4), 0)
                ImageDraw.Draw(im).text((2 - bb[0], 2 - bb[1]), l, font=font, fill=255)
                f = norm(np.array(im))
                ious.append(float((f * m).sum() / max(1.0, ((f + m) > 0).sum())))
            scores.append((float(np.mean(ious)) if ious else 0.0, fi))
        scores.sort(reverse=True)
        best = scores[0][0]
        self._fallback_fonts = [self.fonts[fi] for sc, fi in scores[:3] if sc >= best - 0.04]

    # ── page management ───────────────────────────────────────────────────

    def _new_page(self) -> None:
        """Create a blank A4 RGBA canvas and reset cursor."""
        if self.bank is not None and self.pages:
            self.bank.new_page()
        prog = (1.0 - math.exp(-len(self.pages) / 1.5)) * self.cfg.page_progression
        self._page_scale = 1.0 + 0.25 * prog
        self._page_gap = 1.0 - 0.15 * prog
        self._page_variation = 1.0 + 0.4 * prog
        self._canvas = Image.new(
            "RGBA",
            (self.cfg.page_width, self.cfg.page_height),
            (255, 255, 255, 255),
        )
        self._draw = ImageDraw.Draw(self._canvas)
        # Ballpoint density varies smoothly across the page (not per letter)
        W, H = self.cfg.page_width, self.cfg.page_height
        coarse = np.random.uniform(0.93, 1.0, (max(2, H // 24), max(2, W // 24))).astype(np.float32)
        self._ink_field = cv2.resize(coarse, (W, H), interpolation=cv2.INTER_CUBIC).clip(0.9, 1.0)
        # current writing region (lists / table cells narrow it)
        self._left = float(self.cfg.margin_left)
        self._right = float(self.cfg.page_width - self.cfg.margin_right)
        xh = self._x_height * self._page_scale
        self._margin_drift = random.gauss(0, 0.3 * xh)
        self._page_lean = random.uniform(-0.05, 0.09) * xh   # lines creep right (or left) down the page
        self._line_no = 0
        self._x = self._left + self._margin_offset()
        self._y = float(self.cfg.margin_top)
        self._new_line_params()

    def _full_width(self) -> bool:
        """Writing across the page (not inside a table cell or a narrow column)."""
        return (self._right - self._left) > 0.6 * self.cfg.page_width

    def _margin_offset(self) -> float:
        """Where a line starts relative to the margin. By hand the left edge wanders: a
        slow drift over a few lines, a slight lean down the page, and each line's own
        jitter (a ruler-straight left edge looks typeset). Columns and cells stay put."""
        if not self._full_width():
            return random.uniform(*self.cfg.margin_left_jitter) * 0.5
        xh = self._x_height * self._page_scale
        self._line_no = getattr(self, "_line_no", 0) + 1
        self._margin_drift = max(-1.1 * xh, min(1.1 * xh, 0.8 * getattr(self, "_margin_drift", 0.0)
                                                   + random.gauss(0, 0.3 * xh)))
        lean = max(-1.2 * xh, min(1.2 * xh, getattr(self, "_page_lean", 0.0) * self._line_no))
        return self._margin_drift + lean + random.gauss(0, 0.12 * xh)

    def _new_line_params(self) -> None:
        """Assign random slope, wave parameters, and margin jitter for a new line."""
        f = self._fatigue_multiplier()
        # Slope gets worse with fatigue
        slope_lo, slope_hi = self.cfg.slope_range
        self._line_slope = random.uniform(slope_lo * f, slope_hi * f)
        self._line_start_x = self._x
        # where this line gives up: writers stop before the margin at varying points
        # (the next word won't fit), so the right edge is ragged
        xh = self._x_height * self._page_scale
        self._line_right = self._right - (random.uniform(0.0, 1.4) * xh if self._full_width() else 0.0)
        self._line_char_index = 0
        # Generate multi-harmonic wave components for this line.
        # Each harmonic has a random period, phase, and relative amplitude.
        # Fatigue widens the amplitudes.
        self._harmonics = []
        for i in range(self.cfg.wave_harmonics):
            period = random.uniform(*self.cfg.wave_period_range) / (i + 1)
            phase = random.uniform(0, 2 * math.pi)
            # Higher harmonics get progressively smaller amplitude
            amp_scale = 1.0 / (i + 1) * random.uniform(0.5, 1.5) * f
            self._harmonics.append((period, phase, amp_scale))
        # Slight fatigue recovery on line break (lift pen off paper briefly)
        if self.cfg.fatigue_enabled:
            self._fatigue *= (1.0 - self.cfg.fatigue_line_recovery)

    def _save_current_page(self) -> None:
        if self._canvas is not None:
            if self.cfg.editable:
                # keep the page's own drawings apart from its word layers (for editing)
                drawn = self._canvas.convert("L").getextrema()[0] < 250
                self.page_bases.append(self._canvas if drawn else None)
                self.pages.append(self._compose(len(self.pages)))
            else:
                self.pages.append(self._canvas)

    # ── fatigue helpers ────────────────────────────────────────────────────

    def _fatigue_multiplier(self) -> float:
        """Return the current fatigue multiplier (1.0 = no fatigue).
        Includes random burst chance for sudden sloppiness spikes."""
        if not self.cfg.fatigue_enabled:
            return 1.0
        base = 1.0 + self._fatigue * (self.cfg.fatigue_max - 1.0)
        # Random burst of extra sloppiness
        if random.random() < self.cfg.fatigue_burst_probability * self._fatigue:
            base *= random.uniform(*self.cfg.fatigue_burst_multiplier)
        return base

    def _advance_fatigue(self) -> None:
        """Tick fatigue forward by one character."""
        if not self.cfg.fatigue_enabled:
            return
        self._total_chars_written += 1
        # Fatigue rises on a curve (fast at first, slows near max)
        self._fatigue = min(
            1.0,
            self._fatigue + self.cfg.fatigue_rate * (1.0 - self._fatigue * 0.5)
        )

    def _fatigue_scale(self, base_range: Tuple[float, float]) -> Tuple[float, float]:
        """Scale a (lo, hi) range by the fatigue multiplier."""
        f = self._fatigue_multiplier()
        lo, hi = base_range
        return (lo * f, hi * f)

    # ── character rendering ───────────────────────────────────────────────

    def _render_char(self, char: str, font: ImageFont.FreeTypeFont, font_index: int) -> Tuple[Image.Image, float]:
        """Render one character with rotation, scale, and opacity.
        Fatigue progressively amplifies all imperfection parameters.
        Returns the image and its baseline y within it."""

        if self.bank and self.cfg.vector_fonts:
            vec = self._render_vector_char(char, font)
            if vec is not None:
                return vec

        f = self._fatigue_multiplier()

        # Fatigue-scaled ranges
        rot_range = self._fatigue_scale(self.cfg.rotation_range)
        sx_lo, sx_hi = self.cfg.scale_x_range
        sy_lo, sy_hi = self.cfg.scale_y_range
        # Widen scale ranges with fatigue (push extremes further from 1.0)
        sx_range = (1.0 - (1.0 - sx_lo) * f, 1.0 + (sx_hi - 1.0) * f)
        sy_range = (1.0 - (1.0 - sy_lo) * f, 1.0 + (sy_hi - 1.0) * f)

        # Random parameters
        sx = random.uniform(*sx_range)
        sy = random.uniform(*sy_range)
        if self.bank:
            # match the writer's proportions: capitals / tall letters stand ~1.8 x-heights,
            # small letters ~1.06 (measured on the writer's pieces); fonts differ
            k = self._font_proportion(font, char)
            sx *= k
            sy *= k
        angle = random.uniform(*rot_range)

        # Measure character
        bbox = font.getbbox(char)
        cw = bbox[2] - bbox[0]
        ch = bbox[3] - bbox[1]
        if cw <= 0 or ch <= 0:  # no ink (control / unsupported char): blank, no width
            return Image.new("RGBA", (1, 1), (0, 0, 0, 0)), 0.0

        # Padding for rotation overflow
        pad = max(cw, ch)
        canvas_size = (cw + pad * 2, ch + pad * 2)

        # Draw character centred on a temp mask (inked at the end)
        tmp = Image.new("L", canvas_size, 0)
        draw = ImageDraw.Draw(tmp)
        draw.text((pad - bbox[0], pad - bbox[1]), char, font=font, fill=255)

        # Scale (independent X / Y)
        k = self._word_scale * self._page_scale
        new_w = max(1, int(canvas_size[0] * sx * k))
        new_h = max(1, int(canvas_size[1] * sy * k))
        tmp = tmp.resize((new_w, new_h), Image.BICUBIC)

        # Baseline: text origin (top) + ascent, then follow the scale
        baseline = (pad - bbox[1] + font.getmetrics()[0]) * new_h / canvas_size[1]

        # Rotation (baseline tracked at the glyph's horizontal centre)
        h_before = tmp.height
        tmp = tmp.rotate(angle, resample=Image.BILINEAR, expand=True)
        baseline = tmp.height / 2 + (baseline - h_before / 2) * math.cos(math.radians(angle))

        # Advance fatigue after rendering
        self._advance_fatigue()

        if self.bank:                       # no two font letters identical (like the writer's pieces)
            tmp = self._warp(tmp, self.cfg.glyph_variation * 0.03 * self._x_height)
        mask = self._match_stroke(self._crisp(self._even_out(tmp)))
        if self.bank:                       # lean font letters like the writer's hand
            mask, _ = self._shear_baseline(mask, baseline)
        return self._ink(mask), baseline

    def _render_bank_glyph(self, g: Glyph) -> Tuple[Image.Image, float, float, float]:
        """Scale a bank glyph to the font x-height, jitter it, re-apply slant and ink.
        Returns (image, baseline y, x of the ink start at the baseline, advance width)."""
        # Size varies per word (whole word bigger/smaller, as in the samples), not
        # per piece: letters changing size mid-word is what hurts readability.
        k = self._word_scale * self._page_scale
        sx = k * random.uniform(0.98, 1.02)
        sy = k * random.uniform(0.98, 1.02)
        if g.strokes:
            # Pen-tablet sample: redraw the strokes with a fresh wobble every time.
            # size_fix too: pad words are usually written smaller than the guide lines
            dl: list = []
            mask, base, ink_l, ink_r = render_strokes(
                g.strokes, self._x_height, self._pen_width(), dens=dl,
                jitter=self.cfg.pad_redraw_variation * 0.045,
                sx=sx * g.size_fix * self._widen(g), sy=sy * g.size_fix,
                max_below=1.25 / max(0.3, g.size_fix),   # tails as deep as on paper (1.15-1.3)
                max_tail=0.3 / max(0.3, g.size_fix),     # a short exit, not a trailing smear
                vary=self.cfg.pad_variation, unit=1.0 / max(0.3, g.size_fix),
                y_shift=getattr(g, "base_shift", 0.0))
        else:
            s = self._x_height / (g.ref_xh or self.bank.ref_xh) * g.size_fix
            w = max(1, round(g.mask.width * s * sx * self._widen(g)))
            h = max(1, round(g.mask.height * s * sy))
            mask = self._warp(g.mask.resize((w, h), Image.BICUBIC), self.cfg.glyph_variation * 0.02 * self._x_height)
            mask = self._match_stroke(self._crisp(self._even_out(mask)))
            base = g.baseline * h / g.mask.height
            ink_l = g.ink_left * w / g.mask.width
            ink_r = g.ink_right * w / g.mask.width

        mask, d = self._shear_baseline(mask, base)
        img = self._ink(mask)
        if g.strokes and dl:
            # ink amount (slow parts, landings, retraced and crossing strokes darker)
            dmap, _ = self._shear_baseline(dl[0], base, fill=64)
            img = self._ink_amount(img, dmap)

        for _ in g.label:
            self._advance_fatigue()
        return img, base, d + ink_l, ink_r - ink_l

    @staticmethod
    def _warp(mask: Image.Image, amp: float) -> Image.Image:
        """Smooth random distortion (amp px): a reused scanned piece never comes out
        pixel-identical, the way no two hand-written copies of a word match."""
        if amp <= 0.05:
            return mask
        a = np.array(mask)
        h, w = a.shape
        gh, gw = max(2, h // 22), max(2, w // 22)     # broad shape change, not edge ripple
        dx = cv2.resize(np.random.normal(0, amp, (gh, gw)).astype(np.float32), (w, h), interpolation=cv2.INTER_CUBIC)
        dy = cv2.resize(np.random.normal(0, amp, (gh, gw)).astype(np.float32), (w, h), interpolation=cv2.INTER_CUBIC)
        xs, ys = np.meshgrid(np.arange(w, dtype=np.float32), np.arange(h, dtype=np.float32))
        out = cv2.remap(a, xs + dx, ys + dy, cv2.INTER_LINEAR, borderValue=0)
        return Image.fromarray(out, "L")

    def _shear_baseline(self, mask: Image.Image, base: float, fill: int = 0) -> Tuple[Image.Image, float]:
        """Apply the slant around the baseline: x_out = x_in + (base - y) * t + d.
        Returns the sheared mask and d (where input x=0 lands on the baseline)."""
        t = self._slant_t + self._word_slant
        w, h = mask.size
        d = -min(base * t, (base - h) * t)
        mask = mask.transform((w + math.ceil(abs(h * t)), h), Image.AFFINE,
                              (1, t, -t * base - d, 0, 1, 0), resample=Image.BICUBIC, fillcolor=fill)
        return mask, d

    def _ink_amount(self, img: Image.Image, dens: Image.Image) -> Image.Image:
        """Colour by ink amount like real (semi-transparent) ink: light passes through
        the ink layer, so k layers transmit colour^k (Beer-Lambert). 1 = normal."""
        from glyphbank import ink_amount
        k = ink_amount(dens)
        if k.shape != (img.height, img.width):
            return img
        a = np.array(img)
        c = np.clip(np.array(self.cfg.ink_color, np.float32) / 255, 0.02, 1.0)
        a[..., :3] = np.clip(255 * c[None, None, :] ** k[..., None], 0, 255).astype(np.uint8)
        return Image.fromarray(a, "RGBA")

    def _ink(self, mask: Image.Image) -> Image.Image:
        """Colour an alpha mask with the ink colour at the current pen pressure.
        Pressure drifts smoothly word to word (_next_pressure); ink texture comes from
        one page-wide field at paste time, so neighbouring letters never jump in tone."""
        img = Image.new("RGBA", mask.size, (*self.cfg.ink_color, 0))
        img.putalpha(mask.point(lambda v: int(v * self._pressure / 255)))
        return img

    def _next_word_style(self) -> None:
        """Per-word variation: pen pressure drift and a small slant change."""
        self._next_pressure()
        self._word_font = random.choice(self._fallback_fonts or self.fonts)
        v = self.cfg.glyph_variation * self._page_variation
        # whole-word variation that changes how a word sits, not the letter shapes, so a
        # repeated word never looks like the same picture: lean, tilt, size, pen weight
        self._word_slant = (random.gauss(0, math.tan(math.radians(self.cfg.word_lean_deg)))
                            + random.gauss(0, 0.03 * v))
        self._word_tilt = random.gauss(0, math.radians(self.cfg.word_tilt_deg))
        self._word_x0 = self._x
        self._word_pen = random.uniform(1 - self.cfg.word_weight_var, 1 + 0.45 * self.cfg.word_weight_var)
        self._word_scale = min(1.15, max(0.87, random.gauss(1.0, max(self.cfg.word_size_var, 0.055 * v))))

    def _next_pressure(self) -> None:
        """Random walk of pen pressure within opacity_range (called once per word)."""
        lo, hi = self.cfg.opacity_range
        mid, span = (lo + hi) / 2, max(1.0, hi - lo)
        p = self._pressure + random.gauss(0, 0.08 * span) + 0.2 * (mid - self._pressure)
        self._pressure = min(hi, max(lo, p))

    def _crisp(self, mask: Image.Image) -> Image.Image:
        """Steepen the soft edge an upscaled low-res source gets, so strokes print
        with a pen's sharp edge instead of a blurred halo."""
        if self.cfg.uniform_pen:
            return mask              # _repen redraws the outline anyway
        a = np.array(mask, np.float32)
        # smooth the rough (JPEG-scanned, upscaled) outline first, then re-sharpen it
        sigma = max(0.6, 0.03 * min(a.shape))
        a = cv2.GaussianBlur(a, (0, 0), min(sigma, 1.2))
        t = np.clip((a - 70.0) / 110.0, 0.0, 1.0)
        return Image.fromarray((t * t * (3 - 2 * t) * 255).astype(np.uint8), "L")

    @staticmethod
    def _even_out(mask: Image.Image) -> Image.Image:
        """Bring a scanned piece's darkest strokes to full ink (scans vary word to word)."""
        a = np.array(mask, np.float32)
        ink = a[a > 60]
        if ink.size < 10:
            return mask
        p90 = float(np.percentile(ink, 90))
        if p90 >= 250:
            return mask
        return Image.fromarray(np.clip(a * 255.0 / max(p90, 1.0), 0, 255).astype(np.uint8), "L")

    def _paste_ink(self, img: Image.Image, x: int, y: int) -> None:
        """Paste inked RGBA (page coordinates), modulated by the page's ink-density
        field. When a word layer is active, self._canvas is that layer and
        self._origin its top-left on the page."""
        ox, oy = self._origin
        W, H = self._canvas.size
        lx, ly = x - ox, y - oy
        x0, y0 = max(0, lx), max(0, ly)
        x1, y1 = min(W, lx + img.width), min(H, ly + img.height)
        if x1 <= x0 or y1 <= y0:
            return
        img = img.crop((x0 - lx, y0 - ly, x1 - lx, y1 - ly))
        field = self._ink_field[y0 + oy:y1 + oy, x0 + ox:x1 + ox]
        if field.shape != (y1 - y0, x1 - x0):
            field = np.ones((y1 - y0, x1 - x0), np.float32)
        a = np.array(img.getchannel("A"), np.float32) * field
        img.putalpha(Image.fromarray(a.astype(np.uint8), "L"))
        paste_multiply(self._canvas, img, (x0, y0))

    def _crop(self, box) -> Image.Image:
        ox, oy = self._origin
        return self._canvas.crop((box[0] - ox, box[1] - oy, box[2] - ox, box[3] - oy))

    def _restore(self, img: Image.Image, xy) -> None:
        ox, oy = self._origin
        self._canvas.paste(img, (xy[0] - ox, xy[1] - oy))

    @staticmethod
    def _tight_crop(img: Image.Image) -> Tuple[Image.Image, int, int]:
        """Crop transparent border, return image and offsets."""
        bbox = img.getbbox()
        if bbox is None:
            return img, 0, 0
        cropped = img.crop(bbox)
        return cropped, bbox[0], bbox[1]

    # ── compositing ───────────────────────────────────────────────────────

    def _compute_y_offset(self) -> float:
        """Compute the total vertical offset for the current character:
        baseline jitter + slope (with drift) + multi-harmonic wave + noise.
        All jitter values are scaled by the current fatigue multiplier.
        Returns a float for sub-pixel precision."""
        f = self._fatigue_multiplier()

        # Baseline jitter: word-level or per-character (fatigue-scaled)
        if self.cfg.word_level_baseline:
            jy = self._word_y_offset * f
        else:
            bl = self._fatigue_scale(self.cfg.baseline_jitter)
            jy = random.uniform(min(bl), max(bl))

        # Slope with mid-line drift (slope changes slightly per character)
        # Fatigue makes drift more erratic
        dx = self._x - self._line_start_x
        drift_scale = self.cfg.slope_drift / 50 * f
        self._line_slope += random.uniform(-drift_scale, drift_scale)
        slope_offset = dx * self._line_slope

        # Multi-harmonic waviness (composite of multiple sine waves)
        # (amplitude already fatigue-scaled at line-init time)
        wave_offset = 0.0
        for period, phase, amp_scale in self._harmonics:
            wave_offset += (
                self.cfg.wave_amplitude * amp_scale
                * math.sin(2 * math.pi * dx / max(period, 1.0) + phase)
            )

        # Pure random noise — scaled by fatigue for extra chaos
        noise_range = self._fatigue_scale(self.cfg.noise_y_range)
        noise = random.uniform(min(noise_range), max(noise_range))

        # the word rotates a little around where it starts (per-word tilt)
        tilt = (self._x - self._word_x0) * self._word_tilt
        return jy + slope_offset + wave_offset + noise + tilt

    def _letter_gap(self, scale: float) -> float:
        """Closest ink-to-ink distance to the previous letter, drawn from the writer's
        measured range (layout.json letter_gap, x-heights)."""
        lo, mid, hi = self._letter_gap_q
        # the measurement only sees pen lifts; flowing letters often nearly touch
        if random.random() < 0.3:
            g = random.uniform(0.02, 0.1)
        else:
            g = random.uniform(lo, mid + (hi - mid) * 0.3)
        return max(0.05, g) * self._x_height * self._word_scale * self._page_scale * self._page_gap

    def _place_by_ink(self, img: Image.Image, base: float, shift: Optional[float],
                      joined: bool, scale: float, tok: str = "") -> None:
        """Place a letter/piece by its actual ink: compare, row by row, its left edge
        with the previous letter's right edge and shift it so their closest approach
        equals a gap from the writer's own spacing (joined pieces just touch).
        Up/down jitter is kept, so rows are matched in page coordinates."""
        cropped, cx, cy = self._tight_crop(img)
        if cropped.width <= 1 and cropped.height <= 1:
            return
        xs = 0.0 if shift is None else shift - cx
        y_off = self._compute_y_offset()
        dest_y = int(round(self._y + self._ascent + y_off - (base - cy)))
        a = np.array(cropped.getchannel("A")) > 60
        rows = np.where(a.any(1))[0]
        if len(rows) == 0:
            return
        left = {dest_y + int(r): int(np.argmax(a[r])) for r in rows}
        right = {dest_y + int(r): int(a.shape[1] - 1 - np.argmax(a[r][::-1])) for r in rows}
        x = self._x - xs
        baseline_y = self._y + self._ascent + y_off
        # join with a connecting stroke, at the writer's measured rate (lowercase pairs
        # that weren't already joined in the source piece)
        connect = (bool(self._prev_right) and not joined and self.cfg.letter_joins > 0
                   and self._prev_tok[-1:].islower() and tok[:1].islower()
                   and random.random() < self.cfg.letter_joins)
        if self._prev_right:
            if joined:
                target = -self.cfg.join_overlap
            elif connect:
                target = random.uniform(0.15, 0.32) * self._x_height * self._word_scale * self._page_scale
            else:
                target = self._letter_gap(scale)
            common = [y for y in left if y in self._prev_right]
            if common:
                gap = min(x + left[y] - self._prev_right[y] for y in common)
            else:                       # no shared rows (e.g. a dot): use the extents
                gap = x + min(left.values()) - max(self._prev_right.values())
            lim = 0.8 * self._x_height * self._word_scale
            x += max(-lim, min(lim, target - gap))
        self._paste_ink(cropped, int(round(x)), dest_y)
        if connect:
            self._connect(self._prev_right, {y: x + l for y, l in left.items()}, baseline_y)
        self._line_char_index += 1
        self._prev_right = {y: x + r for y, r in right.items()}
        self._prev_tok = tok
        self._x = x + max(right.values()) + 1

    def _connect(self, prev_right: dict, next_left: dict, baseline_y: float) -> None:
        """A joining stroke from where the previous letter's ink ends (low on its right)
        to where the next one starts (low-to-middle on its left), dipping slightly
        towards the baseline like a real connector."""
        xh = self._x_height * self._word_scale * self._page_scale
        exit_rows = [y for y in prev_right if baseline_y - 0.6 * xh <= y <= baseline_y + 0.08 * xh]
        entry_rows = [y for y in next_left if baseline_y - 0.8 * xh <= y <= baseline_y + 0.05 * xh]
        if not exit_rows or not entry_rows:
            return
        ye = max(exit_rows, key=lambda y: prev_right[y] + 0.3 * (y - baseline_y))   # rightmost, prefer low
        ys = min(entry_rows, key=lambda y: next_left[y] - 0.3 * (y - baseline_y))   # leftmost, prefer low
        xe, xs = prev_right[ye] - 1.0, next_left[ys] + 1.0
        if xs - xe < 1 or xs - xe > 1.2 * xh:
            return
        dip = max(ye, ys) + random.uniform(0.04, 0.14) * xh
        mid = ((xe + xs) / 2, min(dip, baseline_y + 0.05 * xh))
        width = 0.9 * max(self._stroke_px or 0.0, 0.14 * self._x_height)
        self.hand_path([(xe, ye), mid, (xs, ys)], width=width, wobble=0.3)

    def _paste_char(self, char_img: Image.Image, baseline: float,
                    x_shift: Optional[float] = None) -> int:
        """Paste rendered character so its baseline sits on the line's baseline.
        x_shift: image x placed at the cursor (None = left edge of the ink).
        Coordinates are kept as floats internally; only converted to int for paste.
        Returns the effective character width for cursor advancement."""

        cropped, cx, cy = self._tight_crop(char_img)
        w, h = cropped.size
        x_shift = 0.0 if x_shift is None else x_shift - cx

        y_offset = self._compute_y_offset()

        dest_x = int(round(self._x - x_shift))
        dest_y = int(round(self._y + self._ascent + y_offset - (baseline - cy)))

        self._paste_ink(cropped, dest_x, dest_y)
        self._line_char_index += 1

        return w

    # ── cursor & line management ──────────────────────────────────────────

    def _advance_cursor(self, char_width: int) -> None:
        """Move cursor forward by character width + letter spacing + jitter.
        All spacing uses floats for sub-pixel precision."""
        f = self._fatigue_multiplier()
        jr = self._fatigue_scale(self.cfg.letter_spacing_jitter)
        spacing = self.cfg.letter_spacing + random.uniform(min(jr), max(jr))
        # Occasional micro-pause (human hand briefly hesitates)
        pause_prob = self.cfg.micro_pause_probability * f
        if random.random() < pause_prob:
            pr = self._fatigue_scale(self.cfg.micro_pause_range)
            spacing += random.uniform(min(pr), max(pr))
        self._x += char_width + spacing

    def _line_break(self, scale: float = 1.0) -> None:
        self._x = self._left + self._margin_offset()
        gr = self._fatigue_scale(self.cfg.line_gap_jitter)
        lh = self.cfg.line_height * scale * (1 + 0.5 * (self._page_scale - 1))
        # Hand-written line gaps aren't even: a slow drift down the page (a few lines a
        # bit tighter, then a bit looser) plus each gap's own variation, both relative
        # to the line height so wider spacing varies as much as it would by hand.
        irr = self.cfg.line_irregularity
        self._line_rhythm = 0.75 * self._line_rhythm + random.gauss(0, 0.045 * irr)
        rhythm = max(-0.12 * irr, min(0.12 * irr, self._line_rhythm))
        own = max(-0.1 * irr, min(0.1 * irr, random.gauss(0, 0.04 * irr)))
        self._y += lh * (1 + rhythm + own) + random.uniform(min(gr), max(gr))
        self._new_line_params()

    def _needs_page_break(self) -> bool:
        return self._y + self.cfg.line_height > float(self.cfg.page_height - self.cfg.margin_bottom)

    def _page_break(self) -> None:
        self._save_current_page()
        self._new_page()

    # ── word width measurement ────────────────────────────────────────────

    def _plan(self, word: str) -> List[Tuple[str, Optional[dict]]]:
        """How to write a word: [(text, bank glyph meta or None = font letter)].
        With a bank, GlyphBank.plan picks pieces and variants for the whole word so
        they fit together (size, pen weight, slant, joins)."""
        if self.bank:
            return self.bank.plan(word, font_cost=self._font_cost)
        return [(ch, None) for ch in word]

    def _measure_word(self, plan: List[Tuple[str, Optional[dict]]]) -> float:
        """Approximate pixel width of a planned word."""
        font = self._random_font()
        total = 0.0
        for tok, g in plan:
            if g is not None:
                k = self._x_height / (g.get("ref_xh") or self.bank.ref_xh) * g.get("size_fix", 1.0)
                total += (g["ink_right"] - g["ink_left"]) * k * self._widen(g)
            else:
                bbox = font.getbbox(tok)
                total += (bbox[2] - bbox[0])
        word = "".join(t for t, _ in plan)
        # Add average letter spacing
        avg_spacing = self.cfg.letter_spacing + sum(self.cfg.letter_spacing_jitter) / 2.0
        total += avg_spacing * max(0, len(word) - 1)
        return total

    # ── main entry point ──────────────────────────────────────────────────

    # ── writing primitives (also used by docrender for structured documents) ──

    def begin(self) -> None:
        """Start a fresh document."""
        self.pages = []
        self._fatigue = 0.0
        self._total_chars_written = 0
        self.fallback_used = Counter()      # characters written with a font, not the writer's hand
        self.word_recs: list = []           # editable words: page, box, layer, state, text
        self.page_bases: list = []          # per page: non-word drawings (or None)
        self.raw_pages: list = []
        self.proof_log: list = []           # (word, remaining mismatch, attempts) from the reading check
        self._new_page()

    def repeat_report(self) -> List[dict]:
        """Words written with the identical piece more than once on a page because the
        bank lacks copies: [{word, page, repeats, copies}] — worth writing on the pad."""
        if self.bank is None:
            return []
        out = []
        for page, counts in enumerate(self.bank.page_reuse, start=1):
            for label, rep in counts.items():
                if rep >= 2:
                    out.append({"word": label, "page": page, "repeats": rep,
                                "copies": len(self.bank._meta.get(label, []))})
        return sorted(out, key=lambda r: -r["repeats"])

    def finish(self) -> List[Image.Image]:
        self._save_current_page()
        if any(r.get("check") for r in self.word_recs):
            self._proofread_all()
            self.pages = [self._compose(i) for i in range(len(self.pages))]
        self.raw_pages = list(self.pages)
        self._postprocess_all()
        return self.pages

    def word_width(self, word: str, scale: float = 1.0) -> float:
        return self._measure_word(self._plan(word)) * scale * self._page_scale

    def write_word(self, word: str, scale: float = 1.0, wrap: bool = True) -> Tuple[float, float]:
        """Write one word at the cursor (wrapping inside the current region first).
        Returns the x span (start, end) of the ink."""
        plan = self._plan(word)
        width = self._measure_word(plan) * scale * self._page_scale
        if re.fullmatch(r"[?!.,:;)\]'\"]+", word) and self._x > self._line_start_x + 1:
            # punctuation typed with a space before it ("computing ?"): it belongs to the
            # word before - written right after it and never wrapped onto a line alone
            self._x -= 0.8 * self._last_space
            wrap = False
            self._after_question = False
        if self._after_question and wrap and self.cfg.question_break:
            # a question ends its line; the answer starts below with a little extra,
            # uneven room and a slight indent, the way people lay out Q&A notes
            self._after_question = False
            if self._x > self._line_start_x + 1:
                xh = self._x_height * self._page_scale * scale
                self.newline(scale, extra=random.uniform(0.1, 0.55) * self.cfg.line_height * scale)
                self._x += random.uniform(0.0, 1.6) * xh
        elif wrap and self._x + width > getattr(self, "_line_right", self._right) and self._x > self._line_start_x + 1:
            # a short word may still be squeezed in a little past the line's stop
            xh = self._x_height * self._page_scale * scale
            squeeze = (len(word) <= 4 and self._x + width <= self._right + 0.3 * xh
                       and random.random() < 0.5)
            if not squeeze:
                self.newline(scale)
        self._after_question = word.rstrip("\"')]").endswith("?")
        if self.cfg.editable and self._origin == (0, 0):
            return self._write_layered(word, plan, width, scale)
        return self._write_inner(word, plan, width, scale)

    def _write_inner(self, word: str, plan, width: float, scale: float) -> Tuple[float, float]:
        if self.cfg.proofread and self._needs_check(word, plan):
            return self._write_checked(word, plan, width, scale)
        return self._write_plan(plan, scale)

    # ── editable words: each word is its own layer, the page = base + layers ──

    def _word_box(self, width: float, scale: float) -> Tuple[int, int, int, int]:
        xh = self._x_height * self._page_scale * scale
        by = self.baseline_y()
        return (max(0, int(self._x - 2 * xh)), max(0, int(by - 3.6 * xh)),
                min(self.cfg.page_width, int(self._x + width * 1.8 + 5 * xh)),
                min(self.cfg.page_height, int(by + 2.6 * xh)))

    def _write_layered(self, word: str, plan, width: float, scale: float) -> Tuple[float, float]:
        import copy
        box = self._word_box(width, scale)
        state0 = {k: copy.copy(self.__dict__.get(k)) for k in self._STATE}
        layer = Image.new("RGBA", (box[2] - box[0], box[3] - box[1]), (0, 0, 0, 0))
        page_canvas, self._canvas, self._origin = self._canvas, layer, (box[0], box[1])
        # reading check deferred to finish(): all words read together on the GPU
        check = bool(self.cfg.proofread and self._needs_check(word, plan))
        try:
            x0, x1 = self._write_plan(plan, scale)
        finally:
            self._canvas, self._origin = page_canvas, (0, 0)
        self.word_recs.append({"page": len(self.pages), "box": box, "layer": layer, "state": state0,
                               "text": word, "scale": scale, "width": width, "span": (x0, x1),
                               "check": check})
        return x0, x1

    def _proofread_all(self, rounds: int = 2, tries: int = 2) -> None:
        """Read every checked word back in GPU batches; words that read wrong get
        alternatives rendered in their own layer (same start, same state) which are
        read in batches too; the best-reading version is kept."""
        import proofread
        reader = proofread.reader()

        def white(layer):
            bb = layer.getbbox()
            crop = layer.crop(bb) if bb else layer
            bg = Image.new("RGB", crop.size, "white")
            bg.paste(crop, (0, 0), crop)
            return bg

        ks = [k for k, r in enumerate(self.word_recs) if r.get("check")]
        reads = reader.read_batch([white(self.word_recs[k]["layer"]) for k in ks])
        score = {k: proofread.mismatch(t, self.word_recs[k]["text"]) for k, t in zip(ks, reads)}
        used0 = self.fallback_used.copy()
        canvas = self._canvas
        for _ in range(rounds):
            bad = [k for k in ks if score[k] > 0.2]
            if not bad:
                break
            cands = [(k, c) for k in bad for c in self.word_candidates(k, tries)]
            texts = reader.read_batch([white(c) for _, c in cands])
            for (k, c), t in zip(cands, texts):
                m = proofread.mismatch(t, self.word_recs[k]["text"])
                if m < score[k]:
                    score[k] = m
                    self.word_recs[k]["layer"] = self._fit_layer(k, c)
        for k in ks:
            self.word_recs[k].pop("candidates", None)
            if score[k] > 0:
                self.proof_log.append((self.word_recs[k]["text"], round(score[k], 2), 1))
        self.fallback_used = used0
        self._canvas = canvas

    def ink_bbox(self, k: int, layer: Optional[Image.Image] = None) -> Optional[Tuple[int, int, int, int]]:
        """Page-coordinate box of word k's ink."""
        r = self.word_recs[k]
        bb = (layer or r["layer"]).getbbox()
        if bb is None:
            return None
        ox, oy = r["box"][:2]
        return (bb[0] + ox, bb[1] + oy, bb[2] + ox, bb[3] + oy)

    def _fit_layer(self, k: int, layer: Image.Image) -> Image.Image:
        """A replacement wider than the old word could run into the next word on the
        line: squeeze it horizontally (from its left edge) to the space available."""
        r = self.word_recs[k]
        new, old = self.ink_bbox(k, layer), self.ink_bbox(k)
        if new is None or old is None:
            return layer
        limit = self.cfg.page_width - self.cfg.margin_right * 0.5
        for j in range(k + 1, len(self.word_recs)):
            q = self.word_recs[j]
            if q["page"] != r["page"]:
                break
            qb = self.ink_bbox(j)
            if qb and abs(qb[3] - old[3]) < 1.2 * self._x_height:        # same line: the next word
                gap = max(0.4 * self._x_height, qb[0] - old[2])
                limit = min(limit, qb[0] - 0.6 * gap)
                break
        if new[2] <= limit:
            return layer
        width_now, width_max = new[2] - new[0], max(1.0, limit - new[0])
        k_x = max(0.75, width_max / width_now)                       # never squash beyond 75 %
        ox = r["box"][0]
        left = new[0] - ox
        ink = layer.crop((left, 0, layer.width, layer.height))
        ink = ink.resize((max(1, int(round(ink.width * k_x))), ink.height), Image.LANCZOS)
        out = Image.new("RGBA", layer.size, (0, 0, 0, 0))
        out.paste(ink, (left, 0))
        return out

    def _compose(self, page: int) -> Image.Image:
        """Raw page = its non-word drawings (tables, diagrams, math) + its word layers."""
        base = self.page_bases[page]
        out = base.copy() if base is not None else Image.new(
            "RGBA", (self.cfg.page_width, self.cfg.page_height), (255, 255, 255, 255))
        for r in self.word_recs:
            if r["page"] == page:
                paste_multiply(out, r["layer"], r["box"][:2])
        return out

    def _postprocess_all(self, changed=None, regions=None) -> None:
        """Paper effects for every page, or (editing) only for the `changed` pages and the
        sheets whose back they are; unchanged pages keep their finished image."""
        from paper import ink_texture, scanify, show_through
        from concurrent.futures import ThreadPoolExecutor
        n = len(self.raw_pages)
        tex = getattr(self, "_textured", None)
        if changed is None or tex is None or len(tex) != n or len(self.pages) != n:
            changed, tex, out = set(range(n)), [None] * n, [None] * n
        else:
            out = list(self.pages)
        changed = sorted(changed)
        redo = sorted(set(changed) | ({c - 1 for c in changed if c > 0} if self.cfg.show_through else set()))

        def texture(i):
            p = self.raw_pages[i]
            if self.cfg.ink_texture <= 0:
                return p
            if regions and regions.get(i) and tex[i] is not None:
                # an edit: re-texture only the changed word boxes (the texture is local)
                t, m = tex[i].copy(), 16
                for x0, y0, x1, y1 in regions[i]:
                    big = (max(0, x0 - m), max(0, y0 - m), min(p.width, x1 + m), min(p.height, y1 + m))
                    patch = ink_texture(p.crop(big), self.cfg.ink_texture)
                    inner = (x0 - big[0], y0 - big[1], x1 - big[0], y1 - big[1])
                    t.paste(patch.crop(inner), (x0, y0))
                return t
            return ink_texture(p, self.cfg.ink_texture)

        def finish(i):
            p = tex[i]
            if self.cfg.show_through and i + 1 < n:
                p = show_through(p, tex[i + 1], self.cfg.show_through_strength)   # next page = back of this sheet
            return scanify(p) if self.cfg.scan_look else p

        def patch(i, box, m=16):
            """Re-finish one box of page i (front tex[i], back tex[i+1] seen mirrored)."""
            W, H = tex[i].size
            big = (max(0, box[0] - m), max(0, box[1] - m), min(W, box[2] + m), min(H, box[3] + m))
            front = tex[i].crop(big)
            if self.cfg.show_through and i + 1 < n:
                back = tex[i + 1].resize((W, H)).crop((W - big[2], big[1], W - big[0], big[3]))
                front = show_through(front, back, self.cfg.show_through_strength)
            inner = (box[0] - big[0], box[1] - big[1], box[2] - big[0], box[3] - big[1])
            out[i].paste(front.crop(inner), box[:2])

        # pages are independent here; OpenCV/NumPy release the GIL, so threads run in parallel
        with ThreadPoolExecutor(max_workers=min(3, max(1, len(redo)))) as pool:   # memory-bound
            for i, t in zip(changed, pool.map(texture, changed)):
                tex[i] = t
            if regions and not self.cfg.scan_look and all(out[i] is not None for i in redo):
                # an edit: only the edited boxes, and their mirror on the sheet before
                for i, boxes in regions.items():
                    out[i] = out[i].copy()
                    for b in boxes:
                        patch(i, b)
                    if self.cfg.show_through and i > 0:
                        out[i - 1] = out[i - 1].copy()
                        W = tex[i].size[0]
                        for b in boxes:
                            patch(i - 1, (W - b[2], b[1], W - b[0], b[3]))
            else:
                for i, p in zip(redo, pool.map(finish, redo)):
                    out[i] = p
        self._textured = tex
        self.pages = out

    def word_candidates(self, k: int, n: int = 4) -> List[Image.Image]:
        """n alternative renderings of word k (different pieces / variants), each the
        same size as its layer. Kept on the record for apply_candidate."""
        import copy
        r = self.word_recs[k]
        cands = []
        for _ in range(n):
            self.__dict__.update({kk: copy.copy(v) for kk, v in r["state"].items()})
            layer = Image.new("RGBA", r["layer"].size, (0, 0, 0, 0))
            page_canvas, self._canvas, self._origin = self._canvas, layer, r["box"][:2]
            try:
                self._write_plan(self._plan(r["text"]), r["scale"])
            finally:
                self._canvas, self._origin = page_canvas, (0, 0)
            cands.append(layer)
        r["candidates"] = cands
        return cands

    def sentence_range(self, k: int, limit: int = 30) -> List[int]:
        """Indices of the words in the sentence that word k belongs to."""
        end = lambda t: bool(re.search(r"[.!?]['\")\]]*$", t))
        a = k
        while a > 0 and k - a < limit and not end(self.word_recs[a - 1]["text"]):
            a -= 1
        b = k
        while b < len(self.word_recs) - 1 and b - a < limit and not end(self.word_recs[b]["text"]):
            b += 1
        return list(range(a, b + 1))

    def recompose(self, pages, words=None) -> None:
        """Rebuild the given pages from their layers, then the paper effects (once).
        `words`: the edited word indices (their boxes are all that needs re-texturing)."""
        for p in set(pages):
            self.raw_pages[p] = self._compose(p)
        regions = None
        if words is not None:
            regions = {}
            for k in words:
                r = self.word_recs[k]
                regions.setdefault(r["page"], []).append(tuple(r["box"]))
        self._postprocess_all(changed=set(pages), regions=regions)

    def rewrite_word(self, k: int, layer: Optional[Image.Image] = None, plan=None,
                     post: bool = True) -> Image.Image:
        """Replace word k by a candidate layer, or re-render it with `plan` (e.g. a pad
        sample just written for it); rebuild that page. Returns the new final page."""
        import copy
        r = self.word_recs[k]
        if layer is None:
            self.__dict__.update({kk: copy.copy(v) for kk, v in r["state"].items()})
            layer = Image.new("RGBA", r["layer"].size, (0, 0, 0, 0))
            page_canvas, self._canvas, self._origin = self._canvas, layer, r["box"][:2]
            try:
                self._write_plan(plan if plan is not None else self._plan(r["text"]), r["scale"])
            finally:
                self._canvas, self._origin = page_canvas, (0, 0)
        r["layer"] = self._fit_layer(k, layer)
        if post:
            self.recompose([r["page"]], words=[k])
        return self.pages[r["page"]]

    # ── reading check (proofread.py) ──
    _STATE = ("_x", "_y", "_line_slope", "_line_start_x", "_harmonics", "_word_y_offset", "_pressure",
              "_word_slant", "_word_scale", "_word_font", "_prev_right", "_prev_tok", "_fatigue",
              "_total_chars_written", "_line_char_index")

    def _needs_check(self, word: str, plan) -> bool:
        """Words of 3+ letters built from more than one piece (or with font letters);
        a single whole-word piece of the writer's is trusted."""
        if self.bank is None or sum(c.isalnum() for c in word) < 3:
            return False
        return len(plan) > 1 or plan[0][1] is None

    def _write_checked(self, word: str, plan, width: float, scale: float) -> Tuple[float, float]:
        import copy
        import proofread
        reader = proofread.reader()
        xh = self._x_height * self._page_scale * scale
        by = self.baseline_y()
        W, H = self.cfg.page_width, self.cfg.page_height
        box = (max(0, int(self._x - 1.5 * xh)), max(0, int(by - 3.2 * xh)),
               min(W, int(self._x + width * 1.7 + 4 * xh)), min(H, int(by + 2.0 * xh)))
        before = self._crop(box)
        state0 = {k: copy.copy(self.__dict__.get(k)) for k in self._STATE}
        used0 = self.fallback_used.copy()
        best = None
        for attempt in range(3):
            if attempt:                                  # undo the last try exactly
                self._restore(before, box[:2])
                self.__dict__.update({k: copy.copy(v) for k, v in state0.items()})
                self.fallback_used = used0.copy()
                plan = self._plan(word)                  # recently used pieces cost more now
            x0, x1 = self._write_plan(plan, scale)
            crop = self._crop((max(0, int(x0 - 0.4 * xh)), max(0, int(by - 2.8 * xh)),
                               min(W, int(x1 + 0.4 * xh)), min(H, int(by + 1.3 * xh))))
            bg = Image.new("RGB", crop.size, "white")
            bg.paste(crop, (0, 0), crop if crop.mode == "RGBA" else None)
            miss = proofread.mismatch(reader.read(bg), word)
            if best is None or miss < best[0]:
                best = (miss, self._crop(box), {k: copy.copy(self.__dict__.get(k)) for k in self._STATE},
                        self.fallback_used.copy(), (x0, x1))
            if miss <= 0.2:
                break
        if best[0] > 0:
            self.proof_log.append((word, round(best[0], 2), attempt + 1))
        self._restore(best[1], box[:2])                  # keep the best-reading version
        self.__dict__.update(best[2])
        self.fallback_used = best[3]
        return best[4]

    def _write_plan(self, plan, scale: float) -> Tuple[float, float]:
        self._next_word_style()
        self._word_scale *= scale
        if self.cfg.word_level_baseline:
            jr = self._fatigue_scale(self.cfg.word_jitter_y)
            self._word_y_offset = random.uniform(min(jr), max(jr)) * scale
        x0 = self._x
        prev_meta = None
        self._prev_right = None
        self._prev_tok = ""
        for tok, gmeta in plan:
            if gmeta is not None:
                img, base, shift, adv = self._render_bank_glyph(self.bank.load(gmeta))
                joined = _neighbours(prev_meta, gmeta)
            else:
                font = self._random_font()
                img, base = self._render_char(tok, font, 0)
                shift, joined = None, False
                if self.bank:
                    self.fallback_used[tok] += 1
            if self.cfg.ink_spacing:
                self._place_by_ink(img, base, shift, joined, scale, tok)
            elif gmeta is not None:
                if prev_meta is not None:
                    self._x += (-self.cfg.join_overlap if joined
                                else random.uniform(0.06, 0.16) * self._x_height * scale)
                self._paste_char(img, base, shift)
                self._x += adv
            else:
                self._advance_cursor(self._paste_char(img, base))
            prev_meta = gmeta
        x1 = self._x
        # Word spacing — fatigue makes spacing more inconsistent
        f = self._fatigue_multiplier()
        ws_lo, ws_hi = self.cfg.word_spacing
        fatigued_ws = (max(1.0, ws_lo - (f - 1.0) * 4.0), ws_hi + (f - 1.0) * 8.0)
        self._last_space = random.uniform(*fatigued_ws) * self._page_gap * scale
        self._x += self._last_space
        return x0, x1

    def write_text(self, text: str, scale: float = 1.0) -> None:
        for word in text.split():
            self.write_word(word, scale)

    def newline(self, scale: float = 1.0, extra: float = 0.0) -> None:
        self._line_break(scale)
        self._y += extra
        if self._needs_page_break():
            self._page_break()

    def room_left(self) -> float:
        return self.cfg.page_height - self.cfg.margin_bottom - self._y

    def ensure_room(self, height: float) -> None:
        """Start a new page unless `height` px still fit on this one."""
        if self.room_left() < height and self._y > self.cfg.margin_top + 1:
            self._page_break()

    def baseline_y(self) -> float:
        """Page y of the current line's baseline."""
        return self._y + self._ascent

    # glyph placed at an absolute position (math, labels)
    def glyph(self, ch: str, x: float, base_y: float, scale: float = 1.0,
              font: Optional[ImageFont.FreeTypeFont] = None) -> float:
        """Write a single character with its baseline at (x, base_y). Uses the writer's
        own piece when the bank has one, else `font` (or the fallback font).
        Returns the advance width."""
        saved = self._word_scale
        self._word_scale = scale
        try:
            meta = None
            if self.bank and font is None and ch in self.bank:
                meta = self.bank.plan(ch)[0][1]
            if meta is not None:
                img, base, shift, adv = self._render_bank_glyph(self.bank.load(meta))
            else:
                img, base = self._render_char(ch, font or self._random_font(), 0)
                shift, adv = None, None
                if self.bank and not ch.isspace():
                    self.fallback_used[ch] += 1
            cropped, cx, cy = self._tight_crop(img)
            sx = 0.0 if shift is None else shift - cx
            self._paste_ink(cropped, int(round(x - sx)), int(round(base_y - (base - cy))))
            return float(adv if adv is not None else cropped.width)
        finally:
            self._word_scale = saved

    # hand-drawn strokes
    def hand_path(self, pts: List[Tuple[float, float]], width: Optional[float] = None,
                  wobble: float = 1.0, closed: bool = False) -> None:
        """Draw a pen line through pts with a hand's small wobble and pressure."""
        if len(pts) < 2:
            return
        if closed:
            pts = list(pts) + [pts[0]]
        width = width or max(self._stroke_px or 0.0, 0.14 * self._x_height)
        dense = []
        for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
            n = max(2, int(math.hypot(x1 - x0, y1 - y0) / max(2.0, 0.25 * self._x_height)))
            for i in range(n):
                t = i / n
                dense.append((x0 + (x1 - x0) * t, y0 + (y1 - y0) * t))
        dense.append(pts[-1])
        P = np.array(dense, np.float64)
        seg = np.diff(P, axis=0)
        L = np.concatenate([[0], np.cumsum(np.hypot(seg[:, 0], seg[:, 1]))])
        total = max(1.0, L[-1])
        nrm = np.zeros_like(P)
        d = np.gradient(P, axis=0)
        ln = np.hypot(d[:, 0], d[:, 1]) + 1e-6
        nrm[:, 0], nrm[:, 1] = -d[:, 1] / ln, d[:, 0] / ln
        amp = 0.05 * self._x_height * wobble
        off = (amp * np.sin(2 * np.pi * L / (total / random.uniform(0.6, 1.4) + 1) + random.uniform(0, 6.3))
               + 0.5 * amp * np.sin(2 * np.pi * L / max(1.0, 3.0 * self._x_height) + random.uniform(0, 6.3)))
        P = P + nrm * off[:, None]
        pr = 0.85 + 0.15 * np.sin(L / max(1.0, 2.0 * self._x_height) + random.uniform(0, 6.3))
        x0, y0 = P.min(0) - width * 2
        x1, y1 = P.max(0) + width * 2
        S = 2
        W, H = int((x1 - x0) * S) + 2, int((y1 - y0) * S) + 2
        img = Image.new("L", (W, H), 0)
        dr = ImageDraw.Draw(img)
        Q = (P - [x0, y0]) * S
        for i in range(1, len(Q)):
            w = max(1, int(round(width * pr[i] * S)))
            dr.line((Q[i - 1][0], Q[i - 1][1], Q[i][0], Q[i][1]), fill=255, width=w)
            r = w / 2
            dr.ellipse((Q[i][0] - r, Q[i][1] - r, Q[i][0] + r, Q[i][1] + r), fill=255)
        mask = img.resize((max(1, W // S), max(1, H // S)), Image.LANCZOS)
        self._next_pressure()
        self._paste_ink(self._ink(mask), int(round(x0)), int(round(y0)))

    def hand_line(self, x0: float, y0: float, x1: float, y1: float, **kw) -> None:
        # a hand-ruled line bows a little in the middle
        mx, my = (x0 + x1) / 2, (y0 + y1) / 2
        L = math.hypot(x1 - x0, y1 - y0)
        bow = random.gauss(0, 0.008) * L
        nx, ny = (-(y1 - y0) / (L + 1e-6), (x1 - x0) / (L + 1e-6))
        self.hand_path([(x0, y0), (mx + nx * bow, my + ny * bow), (x1, y1)], **kw)

    def hand_arrow(self, x0: float, y0: float, x1: float, y1: float) -> None:
        self.hand_line(x0, y0, x1, y1)
        ang = math.atan2(y1 - y0, x1 - x0)
        h = 0.55 * self._x_height
        for da in (2.6, -2.6):
            a = ang + da + random.gauss(0, 0.08)
            self.hand_path([(x1 + h * math.cos(a), y1 + h * math.sin(a)), (x1, y1)], wobble=0.4)

    def render(self, text: str) -> List[Image.Image]:
        """Parse text, render every character, return list of page images.
        Fatigue builds progressively as characters are written."""
        # Browser textareas send \r\n; tabs / odd whitespace would render as nothing.
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        if self.cfg.clean_markdown and not self.cfg.structured:
            text = clean_markdown(text)
        if self.cfg.structured and not self.cfg.handwriting_model:
            from docrender import render_document
            return render_document(self, text)
        # Blank lines between paragraphs collapse into one paragraph break: hand-written
        # pages use a small paragraph gap (paragraph_spacing), not empty lines.
        text = "\n".join(p for p in (" ".join(line.split()) for line in text.split("\n")) if p)
        if self.cfg.handwriting_model:
            return self._render_with_model(text)
        self.pages = []
        self._fatigue = 0.0
        self._total_chars_written = 0
        self._new_page()

        paragraphs = text.split("\n")

        for pi, para in enumerate(paragraphs):
            words = para.split(" ")
            words = [w for w in words if w]  # drop empties

            for word in words:
                self.write_word(word)

            # Paragraph spacing — partial fatigue recovery (writer pauses)
            if pi < len(paragraphs) - 1:
                self._line_break()
                self._y += self.cfg.paragraph_spacing
                if self.cfg.fatigue_enabled:
                    self._fatigue *= (1.0 - self.cfg.fatigue_paragraph_recovery)
                if self._needs_page_break():
                    self._page_break()

        # Save last page
        self._save_current_page()
        return self.pages

    def _render_with_model(self, text: str) -> List[Image.Image]:
        """Generate short word chunks with Emuru (natural joins, letter variants),
        scale them to the font x-height, slant and ink them, and lay them out with
        the usual margins, word spacing, slope/wave and pagination. Lines wrap on
        the real chunk widths."""
        from wordmodel import StyleWriter, MAX_CHUNK_CHARS

        if not self.cfg.glyph_bank:
            raise ValueError("handwriting_model needs a glyph_bank with labeled words.")
        writer = StyleWriter(self.cfg.glyph_bank)
        if self.cfg.slant_deg is None:
            self._slant_t = math.tan(math.radians(writer.slant_deg))

        self.pages = []
        self._new_page()
        right_edge = self.cfg.page_width - self.cfg.margin_right
        # Chars → px at page scale, from the style; refined by every generated chunk.
        px_per_char: Optional[float] = None

        paragraphs = text.split("\n")
        for pi, para in enumerate(paragraphs):
            words = [w for w in para.split(" ") if w]
            while words:
                # Pack the chunk into the space left on this line (≤ MAX_CHUNK_CHARS).
                room = right_edge - self._x
                est = (lambda n: n * px_per_char) if px_per_char else (lambda n: 0)
                if self._x > self._line_start_x + 1 and est(len(words[0])) > room:
                    self._line_break()
                    if self._needs_page_break():
                        self._page_break()
                    room = right_edge - self._x
                chunk = [words.pop(0)]
                while words:
                    nxt = " ".join(chunk + [words[0]])
                    if len(nxt) > MAX_CHUNK_CHARS or est(len(nxt)) > room:
                        break
                    chunk.append(words.pop(0))
                chunk_text = " ".join(chunk)

                mask, base, xh, ok = writer.write_line(chunk_text)
                if not ok and len(chunk) > 1:   # words dropped: retry as two smaller chunks
                    half = len(chunk) // 2
                    words[:0] = chunk[half:]
                    chunk = chunk[:half]
                    chunk_text = " ".join(chunk)
                    mask, base, xh, ok = writer.write_line(chunk_text)
                s = self._x_height / xh * self._page_scale
                px_per_char = (mask.width * s / len(chunk_text) if px_per_char is None
                               else 0.7 * px_per_char + 0.3 * mask.width * s / len(chunk_text))
                # The model writes neatly and evenly; cut the chunk back into its words and
                # give each the writer's own per-word size / slant / baseline / shape variation.
                pieces = _split_words(mask, len(chunk), 0.45 * xh) or [mask]
                for piece in pieces:
                    self._model_word(piece, base, s, right_edge)

            if pi < len(paragraphs) - 1:
                self._line_break()
                self._y += self.cfg.paragraph_spacing
                if self._needs_page_break():
                    self._page_break()

        self._save_current_page()
        return self.pages

    def _model_word(self, piece: Image.Image, base: float, s: float, right_edge: float) -> None:
        """Place one AI-generated word with the writer's irregularity (model_messiness)."""
        mess = self.cfg.model_messiness
        self._next_word_style()
        # more spread than for the writer's own pieces: the model's output is too regular
        self._word_slant *= 1.0 + mess
        self._word_scale = 1.0 + (self._word_scale - 1.0) * (1.0 + 0.6 * mess)
        k = s * self._word_scale
        w, h = max(1, round(piece.width * k)), max(1, round(piece.height * k))
        base_s = base * h / piece.height
        m = piece.resize((w, h), Image.LANCZOS)
        if mess > 0:
            m = self._warp(m, 0.035 * mess * self._x_height)
        m = self._match_stroke(self._crisp(self._even_out(m)))
        m, d = self._shear_baseline(m, base_s)
        if self._x + w > right_edge and self._x > self._line_start_x + 1:
            self._line_break()
            if self._needs_page_break():
                self._page_break()
        if self.cfg.word_level_baseline:
            jr = self.cfg.word_jitter_y
            self._word_y_offset = random.uniform(min(jr), max(jr)) * (1.0 + 0.5 * mess)
        y_off = self._compute_y_offset()
        self._paste_ink(self._ink(m), int(round(self._x - d)), int(round(self._y + self._ascent + y_off - base_s)))
        self._x += w + random.uniform(*self.cfg.word_spacing) * self._page_gap

    # ── PDF output ────────────────────────────────────────────────────────

    def save_pdf(self, output_path: str) -> None:
        """Convert RGBA pages → RGB and save as a multi-page PDF."""
        if not self.pages:
            raise RuntimeError("No pages rendered. Call render() first.")

        rgb_pages = []
        for page in self.pages:
            rgb = Image.new("RGB", page.size, (255, 255, 255))
            rgb.paste(page, mask=page.split()[3])
            rgb_pages.append(rgb)
        with open(output_path, "wb") as fh:
            fh.write(pages_to_pdf(rgb_pages, photo=self.cfg.scan_look))


def _split_words(mask: Image.Image, n: int, min_gap: float) -> Optional[List[Image.Image]]:
    """Cut a generated chunk into its n words at the n-1 widest blank column runs
    (each at least min_gap px). None if the gaps don't match the word count."""
    if n <= 1:
        return None
    a = np.array(mask) > 60
    ink = a.any(0)
    runs, start = [], None
    for x, v in enumerate(ink):
        if not v and start is None:
            start = x
        elif v and start is not None:
            runs.append((start, x))
            start = None
    cols = np.where(ink)[0]
    if not len(cols):
        return None
    inner = [(a0, b0) for a0, b0 in runs if a0 > cols[0] and b0 <= cols[-1] and b0 - a0 >= min_gap]
    if len(inner) < n - 1:
        return None
    cuts = sorted(sorted(inner, key=lambda r: -(r[1] - r[0]))[:n - 1])
    edges = [0] + [(a0 + b0) // 2 for a0, b0 in cuts] + [mask.width]
    out = []
    for x0, x1 in zip(edges[:-1], edges[1:]):
        part = mask.crop((x0, 0, x1, mask.height))
        bb = part.getbbox()
        if bb is None:
            return None
        out.append(part.crop((bb[0], 0, bb[2], mask.height)))
    return out


def _neighbours(a: Optional[dict], b: Optional[dict]) -> bool:
    """True if piece b directly followed piece a in the same source word (file names
    are <word id>_<piece index>.png), i.e. the cut went through a joining stroke."""
    if not a or not b:
        return False
    wa, _, ka = a["file"].rpartition("_")
    wb, _, kb = b["file"].rpartition("_")
    try:
        return wa == wb and int(kb.split(".")[0]) == int(ka.split(".")[0]) + 1
    except ValueError:
        return False


def _zs_tables() -> Tuple[np.ndarray, np.ndarray]:
    """Zhang-Suen deletion rules for both sub-steps, for every 8-neighbourhood code
    (bit k = neighbour p(k+2), clockwise from north)."""
    t0 = np.zeros(256, bool)
    t1 = np.zeros(256, bool)
    for code in range(256):
        p = [(code >> k) & 1 for k in range(8)]          # p2..p9
        B = sum(p)
        A = sum(1 for k in range(8) if p[k] == 0 and p[(k + 1) % 8] == 1)
        p2, p3, p4, p5, p6, p7, p8, p9 = p
        ok = 2 <= B <= 6 and A == 1
        t0[code] = ok and p2 * p4 * p6 == 0 and p4 * p6 * p8 == 0
        t1[code] = ok and p2 * p4 * p8 == 0 and p2 * p6 * p8 == 0
    return t0, t1


_ZS = _zs_tables()


def _thin(img: np.ndarray) -> np.ndarray:
    """Zhang-Suen thinning of a 0/1 uint8 image to a 1-px centre line
    (table lookup on the 8-neighbourhood code: one pass is a few array ops)."""
    img = (img > 0).astype(np.uint8)
    while True:
        changed = False
        for table in _ZS:
            P = np.pad(img, 1)
            code = (P[:-2, 1:-1] | (P[:-2, 2:] << 1) | (P[1:-1, 2:] << 2) | (P[2:, 2:] << 3)
                    | (P[2:, 1:-1] << 4) | (P[2:, :-2] << 5) | (P[1:-1, :-2] << 6) | (P[:-2, :-2] << 7))
            m = (img == 1) & table[code]
            if m.any():
                img[m] = 0
                changed = True
        if not changed:
            return img


def clean_markdown(text: str) -> str:
    """Turn Markdown into what someone would actually write by hand."""
    import re
    out = []
    for line in text.split("\n"):
        s = line.strip()
        if re.fullmatch(r"[*\-_=#]{1,}", s):            # rules / lone bullets
            out.append("")
            continue
        s = re.sub(r"^#{1,6}\s*", "", s)                  # headings
        s = re.sub(r"^[*+\-]\s+", "- ", s)                # bullets
        s = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", s)   # links / images -> text
        s = re.sub(r"(\*\*|__|\*|`)", "", s)              # emphasis / code marks
        out.append(s)
    return "\n".join(out)


def pages_to_pdf(rgb_pages: List[Image.Image], photo: bool = False) -> bytes:
    """A4 PDF. Clean pages are embedded losslessly as PNG (JPEG block noise around
    strokes looks printed), as grayscale when the ink is neutral (a third of the data).
    photo=True (scanned look: paper grain everywhere) uses high-quality JPEG instead:
    grain makes lossless pages huge and slow, and real scans are JPEG anyway."""
    import io
    import fitz  # PyMuPDF

    doc = fitz.open()
    for img in rgb_pages:
        page = doc.new_page(width=595.28, height=841.89)          # A4 in points
        buf = io.BytesIO()
        if photo:
            img.convert("RGB").save(buf, format="JPEG", quality=90, subsampling=0)
        else:
            a = np.asarray(img.convert("RGB"), np.int16)
            neutral = int(np.abs(a[..., 0] - a[..., 2]).max()) <= 12 and int(np.abs(a[..., 0] - a[..., 1]).max()) <= 12
            (img.convert("L") if neutral else img.convert("RGB")).save(buf, format="PNG", compress_level=6)
        page.insert_image(page.rect, stream=buf.getvalue(), keep_proportion=True)
    data = doc.tobytes(deflate=True, garbage=3)
    doc.close()
    return data


